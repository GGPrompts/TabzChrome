#!/usr/bin/env node
/** Generate the extension's page-dispatched action enum from MCP source. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(repoRoot, 'tabz-mcp-server/src/tools/act-actions.ts');
const outputPath = join(repoRoot, 'extension/shared/actActions.ts');

export function extractPageActions(source) {
  const marker = 'export const PAGE_ACT_ACTIONS = [';
  const start = source.indexOf(marker);
  if (start === -1) throw new Error('Canonical PAGE_ACT_ACTIONS declaration was not found');
  const end = source.indexOf('] as const;', start);
  if (end === -1) throw new Error('Canonical PAGE_ACT_ACTIONS declaration is incomplete');
  const actions = Array.from(
    source.slice(start + marker.length, end).matchAll(/["']([^"']+)["']/g),
    match => match[1]
  );
  if (actions.length === 0 || new Set(actions).size !== actions.length) {
    throw new Error('Canonical PAGE_ACT_ACTIONS must contain unique action names');
  }
  return actions;
}

export function renderExtensionActions(source) {
  const actions = extractPageActions(source);
  return `// Generated by scripts/generate-act-actions.mjs from the canonical MCP source.\n` +
    `// Run npm run generate:act-actions after changing the canonical list.\n` +
    `export const ACT_ACTIONS = [\n` +
    `  ${actions.map(action => `'${action}'`).join(', ')}\n` +
    `] as const\n`;
}

export function assertExtensionActionsCurrent(actual, expected) {
  if (actual !== expected) throw new Error('Extension ACT_ACTIONS is stale. Run npm run generate:act-actions.');
}

function main() {
  const expected = renderExtensionActions(readFileSync(sourcePath, 'utf8'));
  if (process.argv.includes('--check')) {
    assertExtensionActionsCurrent(readFileSync(outputPath, 'utf8'), expected);
    console.log('Extension ACT_ACTIONS is current');
  } else {
    writeFileSync(outputPath, expected);
    console.log('Wrote extension/shared/actActions.ts');
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
